/** The icon for a stored value: a key, or an emoji from before icons. */
export function glyphKey(value: string | null | undefined): GlyphKey | null {
  if (!value) return null;
  if (value in glyphs) return value as GlyphKey;
  return fromEmoji[value] ?? fromEmoji[value.replace(/️/g, '')] ?? 'star';
}

type GlyphProps = {
  name: string | null | undefined;
  size?: number;
  color: string;
  strokeWidth?: number;
  /** Shown when there is no icon at all. */
  fallback?: GlyphKey;
};

/** Draws a stored icon (or an old emoji, as its icon). Decorative: the name says the rest. */
export function Glyph({ name, size = 20, color, strokeWidth = 2, fallback }: GlyphProps) {
  const key = glyphKey(name) ?? fallback;
  if (!key) return null;
  const Icon = glyphs[key];
  return <Icon size={size} color={color} strokeWidth={strokeWidth} />;
}
